// Bakes the NeuraMesh Sans static cuts into src/assets/nm-sans.ts as base64 exports, so the
// control-api bundle carries the face the release card renders with and reads nothing from disk
// at runtime (the seed/skill-seed.ts precedent for generated data). The source of truth is
// packages/fonts (a renamed Geist under the OFL, see its README). Re-run when the fonts rebuild:
//
//   node packages/control-api/scripts/gen-font-asset.mjs
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const here = import.meta.dirname;
const FONTS = resolve(here, '..', '..', 'fonts');
const CUTS = [
  { name: 'MEDIUM', file: 'NeuraMeshSans-Medium.ttf', weight: 500 },
  { name: 'REGULAR', file: 'NeuraMeshSans-Regular.ttf', weight: 400 },
];

// The fallback the brief names: Geist Mono's TTF, if a TTF is what that package ships. Only
// consulted when a NeuraMesh Sans static cut is missing (a woff2-only build), and said out loud.
function geistMonoTtf() {
  const dir = resolve(here, '..', '..', '..', 'node_modules', '@fontsource-variable', 'geist-mono', 'files');
  if (!existsSync(dir)) return null;
  const ttf = readdirSync(dir).find((f) => f.endsWith('.ttf'));
  return ttf ? join(dir, ttf) : null;
}

function pick(cut) {
  const own = join(FONTS, 'files', cut.file);
  if (existsSync(own)) return { path: own, family: 'NeuraMesh Sans', note: `packages/fonts/files/${cut.file}` };
  const woff2 = readdirSync(join(FONTS, 'files')).filter((f) => f.endsWith('.woff2'));
  console.error(`${cut.file} is not in packages/fonts/files (only ${woff2.length} woff2 web faces are). resvg needs TTF bytes.`);
  const mono = geistMonoTtf();
  if (!mono) {
    console.error('No TTF fallback either: @fontsource-variable/geist-mono ships no .ttf. Rebuild packages/fonts (its README) and re-run.');
    process.exit(1);
  }
  console.error(`Falling back to ${mono} for the ${cut.name} cut.`);
  return { path: mono, family: 'Geist Mono Variable', note: mono };
}

const picked = CUTS.map((cut) => ({ ...cut, ...pick(cut), bytes: readFileSync(pick(cut).path) }));
const family = picked[0].family;
const manifest = JSON.parse(readFileSync(join(FONTS, 'manifest.json'), 'utf8'));
const sha = (b) => createHash('sha256').update(b).digest('hex');

const header = `// GENERATED by scripts/gen-font-asset.mjs. Do not edit by hand.
// ${family} static cuts as base64, for the release card renderer (src/releasecard.ts).
// Source: ${picked.map((p) => p.note).join(' and ')}.
// Upstream pin: ${manifest.upstream.repo}@${manifest.upstream.commit.slice(0, 12)} (Geist ${manifest.upstream.version}, OFL 1.1).
${picked.map((p) => `// ${p.file}: ${p.bytes.length} bytes, sha256 ${sha(p.bytes)}`).join('\n')}

export const NM_SANS_FAMILY = ${JSON.stringify(family)};
`;
const body = picked.map((p) => `export const NM_SANS_${p.name}_B64 = '${p.bytes.toString('base64')}';\n`).join('');
const outDir = join(here, '..', 'src', 'assets');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'nm-sans.ts'), header + body);
for (const p of picked) console.error(`${p.name}: ${p.note} (${p.bytes.length} bytes)`);
console.error(`wrote src/assets/nm-sans.ts (${(header.length + body.length).toLocaleString()} chars)`);
