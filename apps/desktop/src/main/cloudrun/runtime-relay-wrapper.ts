// Host wrapper programs carry SDK stdio to the daemon without spawning sandbox children.
import { chmodSync, mkdirSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BOX_TARGETS, RELAY_TICKET_ENV, type BoxTarget } from './runtime-state';
import { FRAME, MAX_FRAME, RELAY_PROTOCOL } from './runtime-relay-protocol';

/** The wrapper's source: plain CommonJS for the image's node, no dependencies, and no way to start a
 *  process (relay-wrapper tests assert it). Exits with the box process's code, or dies of its signal. */
export function relayWrapperSource(o: { node: string; port: number; target: string; targets?: readonly string[] }): string {
  if (!/^\/[A-Za-z0-9/_.+-]+$/.test(o.node) || o.node.length > 120) throw new Error(`The node path ${o.node} cannot be a shebang.`);
  if (!Number.isInteger(o.port) || o.port <= 0 || o.port > 65535) throw new Error('The relay port is not a port.');
  const allowed: readonly string[] = o.targets ?? BOX_TARGETS;
  if (!allowed.includes(o.target) || !/^[a-z][a-z0-9-]*$/.test(o.target)) throw new Error(`No wrapper for ${o.target}.`);
  return `#!${o.node}
'use strict';
// NeuraMesh box relay wrapper for ${o.target} (apps/desktop/src/main/cloudrun/runtime-relay.ts).
// Generated by machined at boot. It runs on the host as an SDK's child and relays argv, cwd, env and
// stdio to machined, which runs ${o.target} inside the agent box. It starts no process of its own.
const net = require('node:net');
const os = require('node:os');
const PORT = ${o.port};
const TARGET = ${JSON.stringify(o.target)};
const T = { HELLO: ${FRAME.HELLO}, STDIN: ${FRAME.STDIN}, STDIN_END: ${FRAME.STDIN_END}, SIGNAL: ${FRAME.SIGNAL}, STDOUT: ${FRAME.STDOUT}, STDERR: ${FRAME.STDERR}, EXIT: ${FRAME.EXIT}, FAIL: ${FRAME.FAIL} };
const MAX = ${MAX_FRAME};
const ticket = process.env[${JSON.stringify(RELAY_TICKET_ENV)}] || '';
const say = (m) => { try { process.stderr.write('nm-box-relay: ' + m + '\\n'); } catch (e) { /* stderr gone */ } };
if (!ticket) { say('no relay ticket in the environment; this wrapper only runs under machined'); process.exit(126); }
const frame = (type, payload) => {
  const b = Buffer.isBuffer(payload) ? payload : Buffer.from(payload || '', 'utf8');
  const h = Buffer.allocUnsafe(5); h.writeUInt8(type, 0); h.writeUInt32BE(b.length, 1);
  return Buffer.concat([h, b]);
};
const signum = (s) => (os.constants.signals && os.constants.signals[s]) || 15;
let done = false;
let signalled = 0;
const finish = (code, signal) => {
  if (done) return; done = true;
  try { process.stdin.destroy(); } catch (e) { /* closed */ }
  const out = () => {
    if (signal && code === null) {
      for (const s of ['SIGTERM', 'SIGINT', 'SIGHUP', 'SIGQUIT']) process.removeAllListeners(s);
      try { process.kill(process.pid, signal); } catch (e) { /* not a signal here */ }
      setTimeout(() => process.exit(128 + signum(signal)), 200);
      return;
    }
    process.exit(typeof code === 'number' ? code : 1);
  };
  process.stdout.write('', () => process.stderr.write('', out));
};
const sock = net.connect({ host: '127.0.0.1', port: PORT });
sock.setNoDelay(true);
const send = (type, payload) => { if (!sock.writable) return true; return sock.write(frame(type, payload)); };
sock.on('connect', () => {
  const env = {};
  for (const k of Object.keys(process.env)) if (typeof process.env[k] === 'string') env[k] = process.env[k];
  send(T.HELLO, JSON.stringify({ v: ${RELAY_PROTOCOL}, ticket: ticket, target: TARGET, argv: process.argv.slice(2), cwd: process.cwd(), env: env }));
  process.stdin.on('data', (c) => { if (!send(T.STDIN, c)) { process.stdin.pause(); sock.once('drain', () => process.stdin.resume()); } });
  process.stdin.on('end', () => send(T.STDIN_END, ''));
  process.stdin.on('error', () => send(T.STDIN_END, ''));
});
let buf = Buffer.alloc(0);
let blocked = false;
const write = (stream, data) => {
  if (!stream.write(data) && !blocked) { blocked = true; sock.pause(); stream.once('drain', () => { blocked = false; sock.resume(); }); }
};
sock.on('data', (chunk) => {
  buf = buf.length ? Buffer.concat([buf, chunk]) : chunk;
  while (buf.length >= 5) {
    const len = buf.readUInt32BE(1);
    if (len > MAX) { say('a frame from machined is over the limit'); finish(125, null); return; }
    if (buf.length < 5 + len) break;
    const type = buf.readUInt8(0);
    const payload = buf.subarray(5, 5 + len);
    buf = buf.subarray(5 + len);
    if (type === T.STDOUT) write(process.stdout, payload);
    else if (type === T.STDERR) write(process.stderr, payload);
    else if (type === T.FAIL) say(payload.toString('utf8').replace(/^nm-box-relay: /, ''));
    else if (type === T.EXIT) {
      let e = { code: 1, signal: null };
      try { e = JSON.parse(payload.toString('utf8')); } catch (err) { /* keep 1 */ }
      finish(e.code === undefined ? 1 : e.code, e.signal || null);
      return;
    }
  }
});
sock.on('error', (e) => { if (!done) { say('machined is unreachable on 127.0.0.1:' + PORT + ' (' + e.message + ')'); finish(125, null); } });
sock.on('close', () => { if (!done) { say('machined closed the relay before ' + TARGET + ' exited'); finish(125, null); } });
for (const s of ['SIGTERM', 'SIGINT', 'SIGHUP', 'SIGQUIT']) {
  process.on(s, () => {
    signalled += 1;
    if (signalled > 1 || !sock.writable) { finish(null, s); return; }
    send(T.SIGNAL, s);
    setTimeout(() => finish(null, s), 15000).unref();
  });
}
`;
}

/** Write one wrapper per target (0700, root's: they are the host's way into the box). Atomic, so an
 *  SDK that spawns while machined rewrites them never runs half a file. */
export function writeRelayWrappers(dir: string, port: number, node: string = process.execPath, extra: readonly string[] = []): Record<BoxTarget, string> & Record<string, string> {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const out: Record<string, string> = {};
  const targets = [...BOX_TARGETS, ...extra];
  for (const target of targets) {
    const file = join(dir, target);
    const tmp = `${file}.${process.pid}.tmp`;
    writeFileSync(tmp, relayWrapperSource({ node, port, target, targets }), { mode: 0o700 });
    chmodSync(tmp, 0o700);
    renameSync(tmp, file);
    out[target] = file;
  }
  return out as Record<BoxTarget, string> & Record<string, string>;
}
