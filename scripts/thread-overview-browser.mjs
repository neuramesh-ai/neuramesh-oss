import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
export async function validate(taskSpace, { space, out, url = 'http://127.0.0.1:5318/thread-overview.html', page = 'p2' }) {
  const p = (await taskSpace(space)).page(page), checks = [];
  const check = (name, ok) => { checks.push({ name, passed: !!ok }); assert.ok(ok, name); };
  const visible = () => p.evaluate(() => !!document.querySelector('.thread-overview'));
  const click = (name) => p.click(`loc=role:button[name="${name}"]`);
  const wait = (show) => p.waitForSelector('.thread-overview', { state: show ? 'visible' : 'hidden' });
  await mkdir(out, { recursive: true });
  try {
    await p.goto(url);
    await p.evaluate(() => { const key = 'nm.thread-overview.v1'; const entries = JSON.parse(localStorage.getItem(key) || '[]'); localStorage.setItem(key, JSON.stringify(entries.filter(([owner]) => !owner.includes('overview-fixture')))); });
    await p.cdp('Emulation.setDeviceMetricsOverride', { width:1440, height:1000, deviceScaleFactor:1, mobile:false });
    await p.reload(); await wait(true);
    check('wide automatic overview reserves a column', await p.evaluate(() => document.querySelector('.thread-overview-body').classList.contains('with-overview')));
    await p.screenshot({ path:join(out, 'wide-dark.png') });
    await p.click('.thread-overview section[aria-label="Progress"] button'); await wait(false);
    await p.waitForFunction(() => document.activeElement?.classList.contains('sdbody'));
    check('row opens detail pane, collapses overview and focuses destination', true);
    await click('Thread overview'); await wait(true);
    await click('Switch tab'); check('tab switch preserves manual reopen', await visible());
    await p.screenshot({ path:join(out, 'pane-manual-reopen.png') });
    await click('Reference screenshot.png'); await p.waitForSelector('.alightbox');
    await p.waitForFunction(() => document.activeElement?.classList.contains('alightboxclose'));
    await p.press('.alightboxclose', 'Escape'); await p.waitForSelector('.alightbox', { state:'hidden' });
    check('source opens its attachment with focus, and Escape does not leave the thread', await p.evaluate(() => !document.body.dataset.escaped));
    await click('Thread overview review.html'); await click('Switch thread'); await click('Resolve artifact');
    check('an artifact finishing after a thread switch cannot navigate the new owner', await p.evaluate(() => !document.body.dataset.openedArtifact));
    await click('Switch thread'); await click('Thread overview'); await wait(true);
    await click('Toggle pane'); await wait(true); await click('Toggle pane'); await wait(false);
    check('next closed-to-open edge collapses again', true);
    await click('Thread overview'); await wait(true); await click('Expand pane'); await wait(false); await click('Expand pane');
    check('expanding the detail pane clears its temporary override', !(await visible()));
    await click('Toggle pane'); await wait(true); await click('Hide thread overview'); await wait(false);
    await click('Toggle pane'); await click('Thread overview'); await wait(true); await click('Toggle pane'); await wait(false);
    check('closed-pane hidden preference survives temporary reopen', true);
    await click('Switch thread'); await wait(true); await click('Switch thread'); await wait(false);
    check('thread preferences remain isolated', true);
    await p.reload(); await wait(false); check('hidden preference survives reload', true);
    await click('Thread overview'); await wait(true); await click('View all 8');
    check('long sections expand explicitly', await p.evaluate(() => document.querySelectorAll('section[aria-label="Artifacts"] .overview-item').length === 8));
    await click('Switch theme'); await p.screenshot({ path:join(out,'wide-light.png') });
    await p.cdp('Emulation.setDeviceMetricsOverride', { width:390, height:844, deviceScaleFactor:1, mobile:false });
    await p.waitForSelector('.overview-popover');
    check('narrow explicit overview remains inside transcript, clear of composer and approvals', await p.evaluate(() => { const card=document.querySelector('.thread-overview').getBoundingClientRect(), gate=document.querySelector('.gateseat').getBoundingClientRect(); return card.left>=0 && card.right<=innerWidth && card.bottom<=gate.top && document.documentElement.scrollWidth<=innerWidth; }));
    await p.screenshot({ path:join(out,'narrow-light.png') });
    await p.focus('.thread-overview'); await p.press('.thread-overview','Escape'); await wait(false);
    check('Escape dismisses popover, returns focus and does not leave thread', await p.evaluate(() => document.activeElement?.classList.contains('overview-toggle') && !document.body.dataset.escaped));
    await click('Thread overview'); await wait(true); await click('Switch theme'); await p.screenshot({ path:join(out,'narrow-dark.png') });
    await click('Hide thread overview'); await click('Switch thread'); await wait(false);
    check('automatic overview stays collapsed on narrow threads', true);
    await p.cdp('Emulation.setDeviceMetricsOverride', { width:1440, height:1000, deviceScaleFactor:1, mobile:false }); await wait(true);
    await click('Toggle empty'); await wait(false); await click('Thread overview'); await wait(true);
    check('empty threads stay quiet but explicit opening explains contents', await p.evaluate(() => !!document.querySelector('.overview-empty')));
    console.log({ checks:checks.length, passed:true, out });
  } finally { await writeFile(join(out,'checks.json'),JSON.stringify(checks,null,2)); }
  console.log(await p.snapshot());
}
