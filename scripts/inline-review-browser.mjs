// Run with ego-browser nodejs in the existing TaskSpace. Uses real components and the production reducer in a labelled fixture.
const assert = (await import('node:assert/strict')).default;
const { mkdir, writeFile } = await import('node:fs/promises');
const { resolve } = await import('node:path');
const task = await taskSpace(Number(process.env.REVIEW_SPACE_ID));
const page = task.page(process.env.REVIEW_PAGE ?? 'p2');
const evidence = resolve('docs/design/code-review-2026-10/evidence');
const checks = [];
const click = async (selector) => { await page.evaluate((s) => document.querySelector(s)?.scrollIntoView({block:'nearest'}), selector); await page.click(selector); };
await mkdir(evidence, { recursive: true });
await page.goto('http://127.0.0.1:5303/engineering-review.html');
await page.waitForSelector('.fixture-controls');
await click('[aria-label="Reset fixture"]');
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1450, height: 980, deviceScaleFactor: 1, mobile: false });
await click('.fixture-controls button:nth-child(2)');
await page.waitForSelector('[data-work-plan="pane"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-work-plan="inline"] button').length), 1);
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="inline"]')?.textContent.includes('Preview')));
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-work-plan="inline"] li').length), 0);
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-work-plan="pane"] ol[aria-label="Work plan steps"] li').length), 4);
checks.push('one full-card plan button with explicit Preview label and steps in the full plan');
await click('[aria-label="Close review panel"]');
await page.focus('[data-work-plan="inline"] button');
await page.keyboard.press('Enter');
await page.waitForSelector('[data-work-plan="pane"]');
checks.push('keyboard opens the complete plan');
await page.screenshot({ path: `${evidence}/inline-plan-preview-dark.png` });
await click('.fixture-controls button:last-child');
await page.waitForSelector('[data-change-review][data-status="proposed"]');
await page.waitForSelector('[aria-label="Code changes"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-change-review] button[aria-label^="Review "]').length), 3);
assert.equal(await page.evaluate(() => !!document.querySelector('.engapproval')), false);
assert.ok(await page.evaluate(() => !!document.querySelector('.fixture-chat [data-change-review] footer')));
checks.push('proposal and approval controls appear inline with three files initially, no duplicate composer card');
await click('[data-change-review] button[aria-expanded]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-change-review] button[aria-label^="Review "]').length), 4);
await click('[data-change-review] button[aria-expanded]');
checks.push('show more and show fewer retain access to every file');
await click('[aria-label="Review test/greeting.test.mjs in this change set"]');
assert.match(await page.evaluate(() => document.querySelector('article header b')?.textContent), /test\/greeting.test.mjs/);
const colors = await page.evaluate(() => {
  const codes = [...document.querySelectorAll('[aria-label="Diff for test/greeting.test.mjs"] code')];
  return [codes.find((c) => c.textContent.includes('greeting, goodbye')), codes.find((c) => c.textContent.includes('{ greeting }'))].map((c) => getComputedStyle(c.parentElement).backgroundColor);
});
assert.notEqual(colors[0], colors[1]);
checks.push('file links open the matching version with distinct added and removed row colors');
await page.screenshot({ path: `${evidence}/inline-changes-proposed-dark.png` });
await click('[data-change-review] footer button:last-child');
await page.waitForSelector('[data-change-review][data-status="applied"]');
assert.equal(await page.evaluate(() => !!document.querySelector('[data-change-review] footer')), false);
checks.push('approved card stays at its original transcript position with Edited status');
await click('.fixture-controls button:last-child');
await page.waitForSelector('[data-change-review][data-status="proposed"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-change-review]').length), 2);
await click('[data-status="applied"] [aria-label="Review src/greeting.mjs in this change set"]');
assert.ok(await page.evaluate(() => document.querySelector('[aria-label="Diff for src/greeting.mjs"]')?.textContent.includes('goodbye engineering')));
assert.equal(await page.evaluate(() => document.querySelector('[aria-label="Diff for src/greeting.mjs"]')?.textContent.includes('goodbye everyone')), false);
checks.push('opening the first batch while a second waits shows the first diff');
await click('[data-status="proposed"] [aria-label="Review src/greeting.mjs in this change set"]');
assert.ok(await page.evaluate(() => document.querySelector('[aria-label="Diff for src/greeting.mjs"]')?.textContent.includes('goodbye everyone')));
await click('[data-status="proposed"] footer button:first-of-type');
await page.waitForSelector('[data-change-review][data-status="declined"]');
checks.push('declined second batch stays separately reviewable');
await page.goto('http://127.0.0.1:5303/engineering-review.html');
await page.waitForSelector('[data-change-review][data-status="declined"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-change-review]').length), 2);
await click('[data-status="applied"] [aria-label="Review src/greeting.mjs in this change set"]');
await page.waitForSelector('[aria-label="Code changes"]');
assert.equal(await page.evaluate(() => document.querySelector('[aria-label="Diff for src/greeting.mjs"]')?.textContent.includes('goodbye everyone')), false);
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-change-review] footer').length), 0);
checks.push('reload retains both batches, exact older file contents and resolved status without approval buttons');
await page.evaluate(() => { document.querySelector('.fixture-chat').scrollTop = document.querySelector('.fixture-chat').scrollHeight; });
await page.screenshot({ path: `${evidence}/inline-review-history-dark.png` });
await click('.review-fixture > header button:last-child');
await page.waitForFunction(() => !document.documentElement.hasAttribute('data-theme-switch'));
await page.screenshot({ path: `${evidence}/inline-review-history-light.png` });
checks.push('review history is readable in light and dark themes');
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 760, height: 1000, deviceScaleFactor: 1, mobile: false });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
await page.screenshot({ path: `${evidence}/inline-review-history-narrow.png` });
checks.push('narrow layout has no horizontal page overflow');
await writeFile(`${evidence}/inline-review-browser-checks.json`, JSON.stringify({ passed: true, checks }, null, 2));
console.log({ passed: true, checks });
