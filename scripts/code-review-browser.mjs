// Run with ego-browser nodejs < scripts/code-review-browser.mjs in the existing review TaskSpace.
// This tests the real components against the explicitly labelled, isolated UI fixture.
const assert = (await import('node:assert/strict')).default;
const { mkdir, writeFile } = await import('node:fs/promises');
const { resolve } = await import('node:path');
const spaceId = Number(process.env.REVIEW_SPACE_ID);
if (!spaceId) throw new Error('Set REVIEW_SPACE_ID to the existing ego-browser TaskSpace.');
const task = await taskSpace(spaceId);
const page = task.page(process.env.REVIEW_PAGE ?? 'p2');
const evidence = resolve(process.env.REVIEW_EVIDENCE ?? 'docs/design/code-review-2026-10/evidence');
await mkdir(evidence, { recursive: true });
await page.goto('http://127.0.0.1:5303/engineering-review.html');
await page.waitForSelector('.fixture-controls');
await page.click('[aria-label="Reset fixture"]');
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1360, height: 920, deviceScaleFactor: 1, mobile: false });
await page.click('.fixture-controls button:first-child');
assert.equal(await page.evaluate(() => !!document.querySelector('[aria-label="Continue in Act mode"]')), false);
await page.waitForFunction(() => document.querySelector('.fixture-title')?.textContent.includes('completed'));
assert.equal(await page.evaluate(() => !!document.querySelector('[aria-label="Continue in Act mode"]')), false);
await page.screenshot({ path: `${evidence}/informational-answer.png` });
await page.click('.fixture-controls button:last-child');
await page.waitForSelector('[aria-label="Code changes"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[aria-label="Changed files"] button').length), 4);
await page.click('button[aria-label="Review test/greeting.test.mjs in this change set"]');
assert.equal(await page.evaluate(() => document.querySelector('article header b')?.textContent), 'test/greeting.test.mjs');
const colors = await page.evaluate(() => {
  const rows = [...document.querySelectorAll('[aria-label="Diff for test/greeting.test.mjs"] code')];
  const added = rows.find((row) => row.textContent.includes('greeting, goodbye'));
  const removed = rows.find((row) => row.textContent.includes('{ greeting }'));
  return [added, removed].map((row) => row ? getComputedStyle(row.parentElement).backgroundColor : null);
});
assert.ok(colors.every(Boolean)); assert.notEqual(colors[0], colors[1]);
await page.screenshot({ path: `${evidence}/review-dark.png` });
await page.click('.review-fixture > header button:last-child');
await page.screenshot({ path: `${evidence}/review-light.png` });
await page.click('button[aria-label="Close review panel"]');
await page.click('.review-fixture > header button:last-child');
assert.equal(await page.evaluate(() => !!document.querySelector('aside')), false, 'Re-rendering must not reopen the same approval');
await page.click('button[aria-label="Review README.md in this change set"]');
assert.equal(await page.evaluate(() => document.querySelector('article header b')?.textContent), 'README.md');
await page.click('.review-fixture aside > nav button:nth-child(2)');
const source = await page.evaluate(() => document.querySelector('[aria-label="File content for README.md"]')?.textContent ?? '');
assert.match(source, /Returns a greeting and a goodbye/); assert.doesNotMatch(source, /Begin Patch|greeting.mjs/);
await page.click('.review-fixture aside > nav button:first-child');
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 980, height: 820, deviceScaleFactor: 1, mobile: false });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
assert.ok(await page.evaluate(() => document.querySelector('[aria-label="Changed files"]').getBoundingClientRect().height <= 160));
await page.screenshot({ path: `${evidence}/review-narrow.png` });
await page.click('[data-change-review] button[aria-expanded]');
await page.click('button[aria-label="Review legacy.txt in this change set"]');
assert.equal(await page.evaluate(() => document.querySelector('article header')?.textContent.includes('Deleted')), true);
await page.click('[data-change-review] footer button:last-child');
await page.waitForFunction(() => document.querySelector('.fixture-title')?.textContent.includes('completed'));
assert.ok(await page.evaluate(() => !!document.querySelector('[data-change-review][data-status="applied"]')), 'Approved changes remain in the transcript');
await page.screenshot({ path: `${evidence}/completed-no-task-prompt.png` });
const result = { passed: true, checks: ['no spurious handoff while streaming or after informational reply', 'automatic review opening', 'unique file list', 'approval file selection', 'distinct addition and deletion colors', 'manual close survives rerender', 'file link reopens selected file', 'source is actual file content', 'narrow layout without overflow', 'deleted file state', 'completed work has no task-conversion banner', 'approved changes remain in the transcript'], themes: ['dark', 'light'] };
await writeFile(`${evidence}/browser-checks.json`, JSON.stringify(result, null, 2));
console.log(result);
