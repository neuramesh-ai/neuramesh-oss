// Rendering + interaction regression. Run via Ego in an existing QA space; no model calls.
const assert = (await import('node:assert/strict')).default;
const { mkdir, writeFile } = await import('node:fs/promises');
const { resolve } = await import('node:path');
const task = await taskSpace(Number(process.env.PREVIEW_SPACE_ID));
const p = task.page(process.env.PREVIEW_PAGE ?? 'p2');
const evidence = resolve(process.env.PREVIEW_EVIDENCE ?? '.nm-evidence/web-preview');
await mkdir(evidence, { recursive: true });
await p.goto('http://127.0.0.1:5303/web-preview.html');
await p.waitForSelector('.webpreview');
const checks = [];
const check = (name, value) => { assert.ok(value, name); checks.push({ name, passed: true }); };
await p.cdp('Emulation.setDeviceMetricsOverride', { width: 1200, height: 850, deviceScaleFactor: 1, mobile: false });
check('multiple cards retain their place between paragraphs', await p.evaluate(() => document.querySelectorAll('.webpreview').length === 2 && document.querySelector('.webpreview')?.nextElementSibling?.textContent?.includes('earlier iteration')));
await p.focus('[aria-label="Open TaskGarden preview in NeuraMesh browser"]');
await p.keyboard.press('Enter');
check('keyboard card opens internally', await p.evaluate(() => document.querySelector('output')?.textContent === 'inapp: http://127.0.0.1:5302/'));
await p.click('[aria-label="Open TaskGarden preview in…"]');
await p.waitForSelector('[role="dialog"]');
check('menu focuses its first action', await p.evaluate(() => document.activeElement?.textContent === 'NeuraMesh browser'));
await p.screenshot({ path: `${evidence}/preview-menu-dark.png` });
await p.keyboard.press('Escape');
await p.waitForSelector('[role="dialog"]', { state: 'hidden' });
check('Escape returns focus to the trigger', await p.evaluate(() => document.activeElement?.getAttribute('aria-label') === 'Open TaskGarden preview in…'));
await p.click('[aria-label="Open TaskGarden preview in…"]');
await p.click('loc=role:button[name="External browser"]');
check('external action chooses the external opener', await p.evaluate(() => document.querySelector('output')?.textContent === 'external: http://127.0.0.1:5302/'));
await p.click('loc=role:button[name="Switch theme"]');
await p.screenshot({ path: `${evidence}/preview-cards-light.png` });
await p.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: false });
check('long titles and addresses fit narrow screens', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
await p.screenshot({ path: `${evidence}/preview-cards-narrow.png` });
await p.click('[aria-label="Open TaskGarden preview in…"]');
check('menu fits narrow viewport', await p.evaluate(() => { const r = document.querySelector('.webpreview-options').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; }));
await p.keyboard.press('Escape');
await p.waitForSelector('[role="dialog"]', { state: 'hidden' });
await p.reload(); await p.waitForSelector('.webpreview');
check('card content re-renders after reload', await p.evaluate(() => document.querySelectorAll('.webpreview').length === 2));
await writeFile(`${evidence}/component-checks.json`, JSON.stringify(checks, null, 2));
console.log({ evidence, checks });
