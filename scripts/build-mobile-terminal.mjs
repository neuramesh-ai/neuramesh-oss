// Bundle the phone's terminal page (apps/mobile/terminal/page.ts — xterm.js + the relay client)
// into ONE html string the WebView can load offline: apps/mobile/src/terminal-html.ts. Generated
// and committed, so the app builds without this script; re-run it when page.ts, the relay client
// or xterm change (`pnpm --filter @neuramesh/mobile terminal:build`). The mobile-cloud round S8.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobile = resolve(here, '..', 'apps', 'mobile');
// esbuild and xterm are the mobile package's dev dependencies (pnpm isolates them there), so
// both resolve from apps/mobile, not from this script's own directory
const require = createRequire(resolve(mobile, 'package.json'));
const { build } = require('esbuild');

const result = await build({
  entryPoints: [resolve(mobile, 'terminal', 'page.ts')],
  bundle: true, write: false, minify: true, format: 'iife', platform: 'browser', target: ['safari16'],
  legalComments: 'none', logLevel: 'error',
});
const js = result.outputFiles[0].text;
const css = readFileSync(require.resolve('@xterm/xterm/css/xterm.css'), 'utf8');

const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
<style>${css}
html,body{margin:0;padding:0;height:100%;background:#141414;overflow:hidden;-webkit-text-size-adjust:100%}
#term{position:absolute;inset:0;padding:6px 4px 0 8px}
.xterm .xterm-viewport{overflow-y:auto}</style></head>
<body><div id="term"></div><script>${js}</script></body></html>`;

const out = resolve(mobile, 'src', 'terminal-html.ts');
writeFileSync(out, `/* eslint-disable */
// GENERATED by scripts/build-mobile-terminal.mjs from apps/mobile/terminal/page.ts — do not edit.
// xterm.js + @neuramesh/relay-client as one page the WebView loads from a string (S8).
export const TERMINAL_HTML = ${JSON.stringify(html)};
`);
console.log(`terminal page: ${(html.length / 1024).toFixed(0)} KB → ${out}`);
