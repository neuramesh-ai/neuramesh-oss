// Run in an existing ego-browser TaskSpace against the labelled local UI fixture.
const assert = (await import('node:assert/strict')).default;
const { mkdir, writeFile } = await import('node:fs/promises');
const { resolve } = await import('node:path');
const spaceId = Number(process.env.REVIEW_SPACE_ID);
if (!spaceId) throw new Error('Set REVIEW_SPACE_ID to the existing ego-browser TaskSpace.');
const task = await taskSpace(spaceId);
const page = task.page(process.env.REVIEW_PAGE ?? 'p2');
const evidence = resolve('docs/design/code-review-2026-10/evidence');
await mkdir(evidence, { recursive: true });
await page.goto('http://127.0.0.1:5303/engineering-review.html');
await page.waitForSelector('.fixture-controls');
await page.click('[aria-label="Reset fixture"]');
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 1360, height: 920, deviceScaleFactor: 1, mobile: false });
await page.click('.fixture-controls button:first-child');
await page.waitForFunction(() => document.querySelector('.fixture-title')?.textContent.includes('completed'));
assert.equal(await page.evaluate(() => !!document.querySelector('[data-work-plan="inline"]')), false);
assert.equal(await page.evaluate(() => !!document.querySelector('aside')), false);
await page.click('.fixture-controls button:nth-child(2)');
await page.waitForSelector('[data-work-plan="pane"]');
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-work-plan="inline"] ol[aria-label="Work plan steps"] li').length), 0);
assert.equal(await page.evaluate(() => !!document.querySelector('[data-work-plan="inline"] details')), false);
assert.equal(await page.evaluate(() => document.querySelector('[data-work-plan="inline"] button')?.getAttribute('aria-label')), 'Open plan');
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="inline"]')?.textContent.includes('4 steps')));
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="inline"]')?.getBoundingClientRect().height < 230));
assert.equal(await page.evaluate(() => document.querySelectorAll('[data-work-plan="pane"] ol[aria-label="Work plan steps"] li').length), 4);
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="pane"]')?.textContent.includes('follows the existing greeting module')));
await page.click('button[aria-label="Close review panel"]');
await page.click('.review-fixture > header button:last-child');
assert.equal(await page.evaluate(() => !!document.querySelector('aside')), false);
await page.evaluate(() => document.querySelector('[data-work-plan="inline"] button')?.scrollIntoView({ block: 'center' }));
await page.click('[data-work-plan="inline"] button');
await page.waitForSelector('[data-work-plan="pane"]');
await page.screenshot({ path: `${evidence}/work-plan-fixture-light.png` });
await page.click('button[aria-label="Close review panel"]');
await page.click('.fixture-controls button:nth-child(2)');
await page.waitForSelector('[data-work-plan="pane"]');
await page.click('.review-fixture > header button:last-child');
await page.screenshot({ path: `${evidence}/work-plan-fixture-dark.png` });
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 760, height: 1000, deviceScaleFactor: 1, mobile: false });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="pane"]')?.clientWidth <= innerWidth));
assert.ok(await page.evaluate(() => document.querySelector('[data-work-plan="inline"]')?.getBoundingClientRect().height < 230));
await page.screenshot({ path: `${evidence}/work-plan-fixture-narrow.png` });
await page.click('.fixture-controls button:last-child');
await page.waitForSelector('[aria-label="Code changes"]');
assert.equal(await page.evaluate(() => !!document.querySelector('[data-work-plan="pane"]')), false);
const result = { passed: true, checks: ['informational answers have no plan card or automatic pane', 'inline preview shows summary and step count without step rows or full source', 'preview stays compact at wide and narrow widths', 'pane opens on proposal with summary and all steps', 'manual close survives rerender', 'Open plan reopens the full plan', 'identical new proposal reopens pane', 'both themes', 'narrow viewport has no horizontal overflow', 'subsequent approval fronts Changes'] };
await writeFile(`${evidence}/work-plan-browser-checks.json`, JSON.stringify(result, null, 2));
console.log(result);
